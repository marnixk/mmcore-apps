"""Inject a complete testhook for Patient Zero. Always writes every TH_* constant."""
from __future__ import annotations

import os

DEFAULTS = {
    "TH_START": -1,
    "TH_FAST": 0,
    "TH_BENCH": 0,
    "TH_SNEEZE": 0,
    "TH_WIN": 0,
    "TH_LIVES": 0,
    "TH_OVER": 0,
    "TH_NOBANNER": 1,
    "TH_PAUSE": 0,
}


def apply(game_dir: str, extra: str) -> None:
    vals = dict(DEFAULTS)
    for kv in extra.split():
        if not kv.strip():
            continue
        key, raw = kv.split("=", 1)
        if key not in vals:
            raise SystemExit(f"unknown hook {key}")
        vals[key] = int(raw)
    lines = [
        "' generated by tools/gametest/hooks/patientzero.py",
        "' TH_START >= 0 skips the title and starts that level.",
        "' TH_FAST <> 0 skips the idle pause in the play loop.",
        "' TH_BENCH 1 prints one BENCH line and ends.",
        "' TH_SNEEZE n forces a sneeze visual from frame n.",
        "' TH_WIN 1 opens the level-clear dialog.",
        "' TH_OVER 1 opens the game-over name entry.",
        "' TH_NOBANNER 1 skips the level banner.",
        "' TH_PAUSE 1 draws one frame and opens the pause dialog.",
    ]
    for key in DEFAULTS:
        lines.append(f"const {key} = {vals[key]}")
    path = os.path.join(game_dir, "includes", "testhook.inc")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
