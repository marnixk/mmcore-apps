"""Inject a complete testhook for Jetpack. Always writes every TH_* constant."""
from __future__ import annotations

import os

DEFAULTS = {
    "TH_START": -1,
    "TH_KILL": 0,
    "TH_GEMS": 0,
    "TH_PHASE": 0,
    "TH_LIVES": 0,
    # The play loop's 4ms pause drains the harness queue inside one spin.
    # Tests skip that wait so a later key is seen on the next logic frame.
    "TH_FAST": 1,
}


def apply(game_dir: str, extra: str) -> None:
    vals = dict(DEFAULTS)
    for kv in extra.split():
        if not kv.strip():
            continue
        key, raw = kv.split("=", 1)
        if key not in vals:
            raise SystemExit(f"unknown hook {key}")
        vals[key] = int(raw)
    lines = [
        "' generated by tools/gametest/hooks/jetpack.py",
        "' TH_START >= 0 skips the title. TH_KILL 1 enemy, 2 spark.",
        "' TH_GEMS leaves one gem and parks the door on the player.",
        "' TH_PHASE paints a light brick in the phaser's tile.",
        "' TH_LIVES > 0 replaces the starting life count.",
        "' TH_FAST <> 0 uses pause 0 in the play loop (harness only).",
    ]
    for key in DEFAULTS:
        lines.append(f"const {key} = {vals[key]}")
    path = os.path.join(game_dir, "includes", "testhook.inc")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")
